FACES = {"glass": GLASS, "barlow": BARLOW, "outfit": OUTFIT}

# rows repeated for a larger size (counted from the capitals' top row; the lowercase x-height is rows 2-7)
CAP_REP = {0: (), 2: (1, 5), 4: (1, 2, 5, 6)}  # capitals and figures: grown about their bars (rows 0, 3, 7)
X_REP = {0: (), 2: (3, 5)}  # the lowercase: about its bar (row 4)
ASC_REP = {0: (), 2: (1, 1)}  # the ascenders' stems above the x-height
D_REP = {0: (), 2: (8, 8)}  # the descenders' stems
CAPS = set("ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!?/%'\"()")


# glyphs grown about other rows than their class's: (capitals' rows, the lowercase's x-height rows)
OWN_REP = {"%": {0: (), 2: (1, 6), 4: (1, 2, 6, 6)}, "x": {0: (), 2: (3, 6)}, ":": {0: (), 2: (4, 5)}, ";": {0: (), 2: (4, 5)}}


# rows a face grows its own way: Barlow's 4 about its diagonal, so its bar stays low (three rows of stem below it, not
# four: the stem read long); its 7 so its slant steps evenly to the baseline; its times sign keeps its size
FACE_REP = {"barlow": {"1": {0: (), 2: (4, 6), 4: (3, 4, 5, 6)}, "4": {0: (), 2: (1, 3), 4: (1, 2, 3, 6)}, "7": {0: (), 2: (1, 7), 4: (1, 3, 5, 7)},
                       "×": {0: (), 2: ()}}}


def grow(ch, glyph, asc, x, d, face=None):
    """The glyph at a size asc rows taller above the x-height, x rows taller in it and d rows longer below it."""
    top, rows = glyph
    own = FACE_REP.get(face, {}).get(ch)
    if own is not None:
        reps = list(own[asc + x] if ch in CAPS else own[x])
        out = []
        for i, r in enumerate(rows):
            out.append(r)
            out.extend([r] * reps.count(top + i))
        return (top, out)
    if ch in CAPS:
        reps = list(OWN_REP.get(ch, CAP_REP)[asc + x])  # (a capital's few rows below the baseline don't grow)
        above = 0  # (a capital starts on row 0: its rows grow, its top stays)
    else:
        # (a comma's tail stays a pixel: only the letters' descenders grow)
        reps = list(ASC_REP[asc] if ch not in "ij" else ()) + list(OWN_REP.get(ch, X_REP)[x]) + list(D_REP[d] if ch not in ",;" else ())
        # i and j: their dot stays a row above the x-height; the rows the ascenders gain are clear space above it
        above = asc if ch in "ij" else sum(1 for r in ASC_REP[asc] if r < top)
        above += sum(1 for r in OWN_REP.get(ch, X_REP)[x] if r < top)
    out = []
    for i, r in enumerate(rows):
        out.append(r)
        out.extend([r] * reps.count(top + i))
    return (top + above, out)
