"""The other looks' lettering, drawn by hand as Classic's is (classic_pixels.py), one set per typeface in its own
character: Glass (Inter: plain, even widths), Barlow (condensed: narrow rounds, tall) and Outfit (geometric: wide
round letters). Every glyph is solid pixels only ("#" ink, "." clear): 2 px stems and 1 row bars,
as the key caps' hand-drawn letters (KEYCAP in make_ui_font.py), corners cut by one pixel.

Each set is drawn at its smallest size: capitals 8 rows, the lowercase 6 (rows 2-7), descenders 2 (rows 8-9). A
larger size repeats rows (grow()): capitals and figures their own rows (CAP_REP, chosen so bars keep their place),
the lowercase rows of the x-height (X_REP), of the ascenders (ASC_REP) and of the descenders (D_REP). The sizes match
the fonts they replace row for row, so no label changes height.
"""


def _g(top, *rows):
    w = max(len(r) for r in rows)
    assert all(len(r) == w for r in rows), rows
    return (top, list(rows))


