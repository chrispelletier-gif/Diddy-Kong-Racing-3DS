def head(glyph):
    """The heading size, 10 rows (as tall as Lilita One's round capitals were at 9): rows HEAD_ROWS (counted from the
    capitals' top) drawn twice. A row repeated in the lowercase's top keeps every letter's body the same height."""
    top, rows = glyph
    out = []
    for i, r in enumerate(rows):
        out.append(r)
        if top + i in HEAD_ROWS:
            out.append(r)
    # a glyph that starts under a repeated row moves down with it
    return (top + sum(1 for h in HEAD_ROWS if h < top), out)
